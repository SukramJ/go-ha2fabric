# Generates licenses/, the licence and notice texts of everything linked into
# the daemon (decision 59 of the 2026-11-23 review, HR-P3-sup-37):
#
#   licenses/MODULES.txt    the linked modules with their versions
#   licenses/go/            the Go standard library's LICENSE and PATENTS
#   licenses/modules/<m>/   per linked module: the licence, notice, authors
#                           and third-party-notices files of the module root,
#                           and its licenses/ directory where it has one
#                           (go-fabric's NOTICE-matter.js.txt, go-fabric-ui's
#                           npm licences of the embedded bundle)
#
# The module set is `go list -deps` of ./cmd/ha2fabric for every release
# target (linux/amd64, linux/arm64, linux/arm), CGO_ENABLED=0. The release
# archive and both images carry the tree.
#
#   script/licenses/generate.sh          write licenses/
#   script/licenses/generate.sh --check  fail when licenses/ is not what the
#                                        generator writes, or when
#                                        THIRD-PARTY-NOTICES.md does not name a
#                                        direct requirement at go.mod's version
set -euo pipefail

cd "$(dirname "$0")/../.."
GO=${GO:-go}

check=0
case "${1:-}" in
--check) check=1 ;;
"") ;;
*) echo "usage: $0 [--check]" >&2; exit 2 ;;
esac

# generate <dir>: write the tree into <dir>, which must be empty.
generate() {
	local out=$1 list mod ver dir f
	list=$(for arch in amd64 arm64 arm; do
		CGO_ENABLED=0 GOOS=linux GOARCH=$arch "$GO" list -deps \
			-f '{{with .Module}}{{if not .Main}}{{.Path}} {{.Version}} {{.Dir}}{{end}}{{end}}' ./cmd/ha2fabric
	done | LC_ALL=C sort -u)
	[ -n "$list" ] || { echo "no linked modules found" >&2; exit 1; }

	mkdir -p "$out/go" "$out/modules"
	local goroot
	goroot=$("$GO" env GOROOT)
	install -m 0644 "$goroot/LICENSE" "$out/go/LICENSE"
	install -m 0644 "$goroot/PATENTS" "$out/go/PATENTS"

	{
		echo "# Generated by script/licenses/generate.sh; do not edit."
		echo "# The modules linked into ha2fabric (linux amd64, arm64, arm), with"
		echo "# their texts under modules/<module>/; the Go standard library's"
		echo "# under go/ (go.mod: go $(awk '/^go /{print $2; exit}' go.mod))."
		echo "$list" | awk '{print $1, $2}'
	} >"$out/MODULES.txt"

	while read -r mod ver dir; do
		[ -d "$dir" ] || { echo "$mod $ver: not in the module cache (go mod download)" >&2; exit 1; }
		local dst="$out/modules/$mod" n=0
		mkdir -p "$dst"
		for f in "$dir"/*; do
			[ -f "$f" ] || continue
			case "$(basename "$f" | tr '[:upper:]' '[:lower:]')" in
			*.go) continue ;;
			licen[cs]e | licen[cs]e[.-]* | copying | copying[.-]* | notice | notice[.-]* | \
				authors | authors[.-]* | contributors | contributors[.-]* | patents | patents[.-]* | \
				third-party-notices*) ;;
			*) continue ;;
			esac
			install -m 0644 "$f" "$dst/$(basename "$f")"
			n=$((n + 1))
		done
		if [ -d "$dir/licenses" ]; then
			(cd "$dir" && find licenses -type f) | LC_ALL=C sort | while read -r f; do
				install -D -m 0644 "$dir/$f" "$dst/$f"
			done
			n=$((n + 1))
		fi
		[ "$n" -gt 0 ] || { echo "$mod $ver: no licence file in the module root" >&2; exit 1; }
	done <<<"$list"
}

if [ "$check" -eq 0 ]; then
	rm -rf licenses
	generate licenses
	echo "licenses/: $(grep -vc '^#' licenses/MODULES.txt) modules"
	exit 0
fi

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
generate "$tmp/licenses"
if ! diff -r licenses "$tmp/licenses" >"$tmp/diff"; then
	head -40 "$tmp/diff"
	echo "licenses/ is stale: run script/licenses/generate.sh and commit the result" >&2
	exit 1
fi

# THIRD-PARTY-NOTICES.md names every direct requirement as
# "module `<path>`, pinned `<version>`" (HR-P3-doc-38).
fail=0
while read -r mod ver; do
	grep -qF "module \`$mod\`, pinned \`$ver\`" THIRD-PARTY-NOTICES.md ||
		{ echo "THIRD-PARTY-NOTICES.md: no \"module \`$mod\`, pinned \`$ver\`\"" >&2; fail=1; }
done < <("$GO" mod edit -json | awk '
	/"Require": \[/ {inreq=1; next}
	inreq && /^\t\]/ {inreq=0}
	inreq && /"Path":/ {gsub(/[",]/, "", $2); p=$2}
	inreq && /"Version":/ {gsub(/[",]/, "", $2); v=$2}
	inreq && /"Indirect": true/ {ind=1}
	inreq && /^\t\t}/ {if (!ind) print p, v; p=""; v=""; ind=0}')
[ "$fail" -eq 0 ] || exit 1
echo "licenses/ is current; THIRD-PARTY-NOTICES.md names every direct requirement"
